// Generates repair_encoding.sql: restores the text that was destroyed while
// load_legacy.sql was applied to the cloud on 2026-07-22.
//
// WHAT HAPPENED
// The runbook's apply step piped the loader through PowerShell into a native
// process:
//
//   Get-Content ./load_legacy.sql -Raw -Encoding UTF8 | docker exec -i ... psql
//
// Get-Content decoded the file correctly. The pipe did not: Windows PowerShell
// 5.1 re-encodes text on its way into a native command using $OutputEncoding,
// which defaults to ASCII, and its replacement fallback emits a literal '?' for
// every character it cannot represent — one per UTF-16 code unit, so an emoji
// (a surrogate pair) becomes two and a flag emoji becomes four. ASCII passed
// through untouched, which is why the damage reads as ordinary text with holes
// in it rather than as an obvious failure.
//
// The signature is exact and was verified against all 133 migrated rows: the
// stored value equals the snapshot value with every non-ASCII UTF-16 code unit
// replaced by '?'. Nothing else differs. Values the legacy system had already
// stored as JSON survived intact, because \uXXXX escapes are themselves ASCII.
//
// The 47 posts collected since by the `ingest` function are unaffected — Deno's
// Response.json() decodes UTF-8 and nothing re-encodes on the way to Postgres.
// This is migration damage, not a pipeline bug, and it cannot recur through
// ingest.
//
// WHAT THIS EMITS
// One guarded UPDATE per damaged value. Each carries `and md5(<col>) = '<hash
// of the damaged text>'`, so the script:
//   - is idempotent (a second run matches nothing),
//   - refuses to overwrite anything that is not in the exact damaged state,
//   - and is a no-op against a database that was loaded correctly.
//
// Read-only against SQLite. Emits a single transactional SQL script.
//
//   node scripts/build_encoding_repair.mjs legacy_snapshot.db repair_encoding.sql
//
// Apply it the way §5 of docs/cloud-migration-runbook.md now says to apply
// load_legacy.sql — psql reading the file itself, never a shell pipe. Applying
// this repair through the pipe that caused the damage would simply reproduce it.
import { DatabaseSync } from 'node:sqlite'
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'

const db = new DatabaseSync(process.argv[2], { readOnly: true })
const out = []
const W = (s) => out.push(s)

const S = (v) => `'${String(v).replace(/'/g, "''")}'`
const md5 = (s) => createHash('md5').update(s, 'utf8').digest('hex')

/**
 * Reproduce the damage. Iterating with a for..of yields code POINTS, so an
 * astral character is one iteration — but the encoder that did this worked on
 * UTF-16 code UNITS and emitted a '?' for each, which is why the corpus shows
 * '????' where the Italian flag used to be. Hence the length check.
 */
const damaged = (clean) => {
  let out = ''
  for (const ch of clean) {
    out += ch.codePointAt(0) < 128 ? ch : '?'.repeat(ch.length)
  }
  return out
}

const counts = new Map()

/** One guarded UPDATE, or nothing when the value lost no characters. */
const repair = (table, column, clean, where) => {
  if (clean === null || clean === undefined) return
  const broken = damaged(clean)
  if (broken === clean) return
  W(`update public.${table} set ${column} = ${S(clean)} where ${where} and md5(${column}) = '${md5(broken)}';`)
  const key = `${table}.${column}`
  counts.set(key, (counts.get(key) ?? 0) + 1)
}

W('-- Generated by build_encoding_repair.mjs from the Phase 1 SQLite snapshot.')
W('-- Restores text lost to an ASCII re-encode while load_legacy.sql was applied.')
W('-- Every statement is guarded on the damaged md5: idempotent, and inert')
W('-- against any value that is not in the exact expected damaged state.')
W('begin;')
W('')

// --- raw_posts: the root. Everything downstream is derived from post_text. ---
// content_hash is `generated always as (md5(post_text))`, so it corrects itself
// and must not be assigned here.
W('-- raw_posts: keyed on legacy_id, the legacy composite key the loader kept.')
for (const r of db.prepare('select id, post_text, author from raw_posts').all()) {
  const where = `legacy_id = ${S(r.id)}`
  repair('raw_posts', 'post_text', r.post_text, where)
  repair('raw_posts', 'author', r.author, where)
}
W('')

// --- normalized_posts -------------------------------------------------------
// The loader gave these fresh uuids, so they are reached through raw_posts.
W('-- normalized_posts: reached through raw_posts, which holds the legacy key.')
for (const n of db.prepare('select raw_post_id, clean_text from normalized_posts').all()) {
  repair('normalized_posts', 'clean_text', n.clean_text,
    `raw_post_id = (select id from public.raw_posts where legacy_id = ${S(n.raw_post_id)})`)
}
W('')

// --- editorial_assets / traceability_links ---------------------------------
// Both kept their legacy uuid as the primary key.
W('-- editorial_assets and traceability_links kept their legacy uuids.')
for (const e of db.prepare('select id, generated_text from editorial_assets').all()) {
  repair('editorial_assets', 'generated_text', e.generated_text, `id = ${S(e.id)}::uuid`)
}
for (const l of db.prepare('select id, claim_text from traceability_links').all()) {
  repair('traceability_links', 'claim_text', l.claim_text, `id = ${S(l.id)}::uuid`)
}

W('')
W('commit;')

writeFileSync(process.argv[3], out.join('\n') + '\n', 'utf8')

let total = 0
for (const [k, n] of [...counts].sort()) {
  console.log(`${k.padEnd(34)} ${n}`)
  total += n
}
console.log(`statements=${total}`)
console.log(`wrote ${process.argv[3]}`)
db.close()
